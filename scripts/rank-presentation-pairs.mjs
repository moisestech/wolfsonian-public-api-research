import { readFileSync, writeFileSync } from 'node:fs';
import { MATRIX_OBJECTS } from '../src/matrix-objects.mjs';
import { conversationRecords } from '../src/lakehouse-matches.mjs';
import { societyView } from '../src/archive-society.mjs';
import { localImageUrl } from '../src/local-images.mjs';

const packet = JSON.parse(readFileSync(new URL('../data/lakehouse/project-matches.json', import.meta.url), 'utf8'));
const graph = conversationRecords(packet);
const captured = new Set(graph.records.map(record => record.accession));

function scoreOf(reason) {
  const peers = Math.max(1, reason.candidateCount || 1);
  const contribution = reason.contribution || 1;
  return contribution / Math.sqrt(peers);
}

const pairs = [];
for (const record of graph.records) {
  if (!localImageUrl(record.accession)) continue;
  const edge = societyView(graph.records, record.accession, 'family').edges[0];
  if (!edge || !localImageUrl(edge.target) || !captured.has(edge.target)) continue;
  const reason = edge.reasons?.[0];
  if (!reason?.value || reason.value === 'Unlabeled') continue;
  pairs.push({
    source: record.accession,
    sourceTitle: record.title,
    target: edge.target,
    targetTitle: graph.records.find(item => item.accession === edge.target)?.title || '',
    tag: reason.value,
    family: reason.family,
    candidateCount: reason.candidateCount || 0,
    score: Number(scoreOf(reason).toFixed(3)),
  });
}
pairs.sort((a, b) => b.score - a.score || a.candidateCount - b.candidateCount || a.source.localeCompare(b.source));
const seen = new Set();
const unique = [];
for (const pair of pairs) {
  const key = [pair.source, pair.target].sort().join('|');
  if (seen.has(key)) continue;
  seen.add(key);
  unique.push(pair);
}

const missingPhotographs = MATRIX_OBJECTS.filter(object => !localImageUrl(object.accession)).map(object => ({
  accession: object.accession,
  title: object.title,
}));

const opening = unique[0]?.source || '';
const payload = {
  openingAccession: opening,
  note: 'A shared tag is not a historical relationship. Pairs are existing matrix objects with two local photographs and a saved lookup.',
  pairs: unique.slice(0, 12),
  missingPhotographs,
};
writeFileSync(new URL('../data/lakehouse/presentation-pairs.json', import.meta.url), JSON.stringify(payload, null, 2) + '\n');
const moduleText = `/** Generated by scripts/rank-presentation-pairs.mjs. A shared tag is not a historical relationship. */\nexport const OPENING_ACCESSION = ${JSON.stringify(opening)};\nexport const PRESENTATION_PAIRS = Object.freeze(${JSON.stringify(unique.slice(0, 12), null, 2)});\nexport const MISSING_PHOTOGRAPHS = Object.freeze(${JSON.stringify(missingPhotographs, null, 2)});\n`;
writeFileSync(new URL('../src/presentation-pairs.mjs', import.meta.url), moduleText);
console.log('Opening ' + opening + ' · ' + unique.length + ' photographed pairs · ' + missingPhotographs.length + ' missing photographs');
