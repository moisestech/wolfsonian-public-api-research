import { readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const imageDir = resolve(root, '../wolfsonian-public-api-research/data/data-images-wolfsonian-archive-dreams-in-public');
const files = (await readdir(imageDir)).filter(name => name.toLowerCase().endsWith('.jpg') && !name.startsWith('.')).sort();
const map = {};
for (const file of files) map[file.replace(/\.jpe?g$/i, '')] = file;
const body = '/** Generated by scripts/index-local-images.mjs. Filenames only; the photographs stay outside this repo. */\nexport const LOCAL_IMAGE_FILES = Object.freeze(' + JSON.stringify(map, null, 2) + ');\n';
await writeFile(new URL('../src/local-image-index.mjs', import.meta.url), body);
console.log('Indexed ' + files.length + ' local object images.');
